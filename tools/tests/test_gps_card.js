const assert=require('assert/strict');
const fs=require('fs'),path=require('path'),vm=require('vm');
const html=fs.readFileSync(path.resolve(__dirname,'../../competition_backend/competition_backend/web/index.html'),'utf8');
const script=html.match(/<script>([\s\S]*?)<\/script>/g).map(s=>s.replace(/^<script>|<\/script>$/g,'')).join('\n');
new vm.Script(script);
const source=html.slice(html.indexOf('function GPS卡片数据('),html.indexOf('function 实时数值('));
const ctx={转义:String};vm.createContext(ctx);vm.runInContext(source,ctx);
const valid={connected:true,received_at:100,gps_telemetry_age_seconds:0,location_source:4,gps_status:6,gps_num:22};
const show=(extra={},time=100)=>ctx.GPS卡片数据({...valid,...extra},time);
assert.equal(show().status,'RTK 固定');assert.equal(show().satellites,'22');
assert.equal(show({gps_status:5}).status,'RTK 浮点');
assert.equal(show({connected:false}).status,'—');assert.equal(show({received_at:90}).status,'已过期');
assert.equal(show({gps_telemetry_age_seconds:2.5},101).status,'已过期');
assert.equal(show({location_source:10}).status,'未启用');assert.equal(show({gps_num:0}).satellites,'0');
for(const gps_num of [255,-1,NaN,null,undefined,''])assert.equal(show({gps_num}).satellites,'—');
const healthy={state:'normal',age_seconds:.1,count:10};
assert.equal(ctx.心跳显示(healthy).color,'heartbeat-normal');
assert.equal(ctx.心跳显示({...healthy,age_seconds:4}).color,'heartbeat-abnormal');
assert.equal(ctx.心跳显示({...healthy,peer_age_seconds:4}).color,'heartbeat-unknown');
for(const age_seconds of [null,undefined,NaN,-1])assert.equal(ctx.心跳显示({...healthy,age_seconds}).text,'未知');
assert.equal(ctx.心跳显示(null).text,'未知');
// GPS 固定解不能伪造正常心跳；GPS 未定位也不能把正常心跳变红。
assert.match(ctx.GPS卡片指标(valid,100,{state:'abnormal',age_seconds:9}),/heartbeat-abnormal/);
assert.match(ctx.GPS卡片指标({...valid,gps_status:1},100,healthy),/heartbeat-normal/);
assert.match(ctx.GPS卡片指标(null,100,null),/heartbeat-unknown/);
const detail=ctx.GPS详情指标(valid,100,healthy);
for(const text of ['GPS 状态','GPS 星数','心跳包异常'])assert.ok(detail.includes(text));
assert.ok(detail.includes('<strong>无</strong>'));
assert.ok(!html.includes('rtk-indicator'));assert.ok(!html.includes('EGO 状态'));
assert.ok(html.includes('GPS详情指标(telemetry,当前状态.server_time,当前状态.prometheus_heartbeat?.[String(id)])'));
assert.ok(html.includes('class="metric communication-metric" data-traffic-uav-id="${id}"'));
console.log('GPS 数据、独立心跳颜色、详情展示与失效数据检查通过。');
